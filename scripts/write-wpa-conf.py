#!/usr/bin/env python3
"""Write a real wpa_supplicant.conf on a MOUNTED card.

`wpa_supplicant -c <missing file>` HANGS in the foreground — it is not an
error, it just waits. That cost a whole debugging cycle, so the config is
created here rather than discovered there.

Only the interface, ctrl socket and country are set. No PSK is written to
disk; `Lasagna` credentials go in at runtime via `wpa_cli set_network` /
`wpa_passphrase`, or by Nick if he prefers them on the card.

    sudo python3 scripts/write-wpa-conf.py /mnt/usbsd
"""
import os
import subprocess
import sys
import time

CARD = sys.argv[1] if len(sys.argv) > 1 else "/mnt/usbsd"

CONF = """# Generated by scripts/write-wpa-conf.py
# Auto-generated: interfaces, control socket and regulatory country.
# No pre-shared key is stored here on purpose.

country=US
ctrl_interface=DIR=/var/run/wpa_supplicant GROUP=root MODE=0660
update_config=1
eapol_version=2
ap_scan=1

# Fast roaming across the 2.4/5 GHz bands; this board is 2x2-ish capable
# but the fitted antenna is single-IPEX (1x1), so keep it simple.
network={
    key_mgmt=WPA-PSK
    scan_ssid=1
}
"""


def main():
    etc = os.path.join(CARD, "etc/wpa_supplicant")
    os.makedirs(etc, exist_ok=True)
    path = os.path.join(etc, "wpa_supplicant.conf")
    if os.path.exists(path):
        bak = path + ".pre-" + time.strftime("%Y%m%d-%H%M%S")
        subprocess.run(["cp", "-a", path, bak], check=False)
        print("backed up -> %s" % os.path.basename(bak))
    with open(path, "w") as fh:
        fh.write(CONF)
    os.chmod(path, 0o644)
    print("wrote %s (%d B)" % (path, os.path.getsize(path)))
    print("--- verify readback ---")
    with open(path) as fh:
        head = [next(fh).rstrip() for _ in range(6)]
    for h in head:
        print("   ", h)
    return 0


if __name__ == "__main__":
    sys.exit(main())